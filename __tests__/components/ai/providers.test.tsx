import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
vi.mock('@/features/auth/hooks/useSession', () => ({ useSession: () => ({ user: { id: 'owner' }, loading: false }) }))
import { AIProvidersManager } from '@/features/ai/components/AIProvidersManager'
afterEach(() => { cleanup(); vi.unstubAllGlobals() })
const result = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status })
it('shows load errors and retries rather than pretending there are no keys', async () => {
  const fetcher = vi.fn().mockResolvedValueOnce(result({ error: 'Try later' }, 503)).mockResolvedValueOnce(result({ keys: [] }))
  vi.stubGlobal('fetch', fetcher)
  render(<AIProvidersManager ownerId="owner" />)
  expect(await screen.findByRole('alert')).toHaveTextContent('Try later')
  fireEvent.click(screen.getByRole('button', { name: 'Retry loading providers' }))
  await screen.findByLabelText('OpenAI API key')
  expect(fetcher).toHaveBeenCalledTimes(2)
})
it('uses accessible forms, blocks duplicate submissions and clears plaintext after saving', async () => {
  let resolve!: (r: Response) => void
  const pending = new Promise<Response>(r => { resolve = r })
  const fetcher = vi.fn().mockResolvedValueOnce(result({ keys: [] })).mockReturnValueOnce(pending)
  vi.stubGlobal('fetch', fetcher)
  render(<AIProvidersManager ownerId="owner" />)
  const input = await screen.findByLabelText('OpenAI API key')
  fireEvent.change(input, { target: { value: 'test-secret-1234' } })
  const button = screen.getByRole('button', { name: 'Save OpenAI key' })
  fireEvent.submit(input.closest('form')!)
  fireEvent.submit(input.closest('form')!)
  expect(fetcher).toHaveBeenCalledTimes(2)
  expect(button).toBeDisabled()
  await act(async () => resolve(result({ provider: 'openai', key_preview: '...1234', is_valid: null, last_verified_at: null })))
  await waitFor(() => expect(input).toHaveValue(''))
  expect(screen.getByText(/\.\.\.1234/)).toBeVisible()
  expect(screen.getByRole('button', { name: 'Verify OpenAI key' })).toBeVisible()
})
it('keeps input on failure and provides a removal confirmation', async () => {
  vi.stubGlobal('fetch', vi.fn().mockResolvedValueOnce(result({ keys: [{ provider: 'openai', key_preview: '...1234', is_valid: true, last_verified_at: null }] })).mockResolvedValueOnce(result({ error: 'Retry save' }, 503)))
  render(<AIProvidersManager ownerId="owner" />)
  const input = await screen.findByLabelText('OpenAI API key')
  fireEvent.change(input, { target: { value: 'new-secret-1234' } })
  fireEvent.submit(input.closest('form')!)
  expect(await screen.findByRole('alert')).toHaveTextContent('Retry save')
  expect(input).toHaveValue('new-secret-1234')
  fireEvent.click(screen.getByRole('button', { name: 'Remove OpenAI key' }))
  expect(screen.getByRole('button', { name: 'Confirm remove OpenAI key' })).toBeVisible()
})
